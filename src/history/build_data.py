#!/usr/bin/env python3
"""История мира: собирает src/history/data.json из текстов src/history/raw/*.txt.
Строка государства: id|Название|начало|конец|регион|сфера|Описание|флаги (a — начало примерно, b — конец примерно)
Строка события (5_events.txt): id|год|Название|Описание|регион|важность 1–3
Годы до н. э. — отрицательные, 2026 — «существует сейчас». Запуск: python3 src/history/build_data.py"""
import glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
NOW = 2026
REGIONS = [
    ['we', 'Западная Европа', 'Британия, Франция, Пиренеи, Нидерланды'],
    ['ce', 'Центральная Европа и Италия', 'Германия, Италия, Австрия, Польша, Чехия, Венгрия'],
    ['sc', 'Северная Европа и Прибалтика', 'Скандинавия, Финляндия, Прибалтика'],
    ['bal', 'Греция, Балканы, Византия', 'Греция, Болгария, Сербия, Румыния'],
    ['ee', 'Восточная Европа и Россия', 'Русь, Россия, Украина, Беларусь, степи Причерноморья'],
    ['me', 'Ближний Восток', 'Месопотамия, Анатолия, Сирия, Палестина, Аравия'],
    ['eg', 'Египет и Северная Африка', 'Египет, Ливия, Тунис, Алжир, Марокко'],
    ['af', 'Африка южнее Сахары', 'Нубия, Эфиопия, Западная, Восточная и Южная Африка'],
    ['ir', 'Иран и Кавказ', 'Иран, Афганистан, Армения, Грузия, Азербайджан'],
    ['ca', 'Средняя Азия, степь, Сибирь', 'Казахстан, Узбекистан, Монголия, Сибирь'],
    ['in', 'Индия', 'Индия, Пакистан, Бангладеш, Шри-Ланка'],
    ['cn', 'Китай', 'Китай, Тибет, Тайвань'],
    ['kj', 'Корея и Япония', 'Корея, Япония'],
    ['sea', 'Юго-Восточная Азия', 'Вьетнам, Камбоджа, Таиланд, Мьянма, Индонезия, Филиппины'],
    ['na', 'Северная Америка', 'США, Канада, Арктика'],
    ['mz', 'Мезоамерика и Карибы', 'Мексика, Центральная Америка, острова Карибского моря'],
    ['sa', 'Южная Америка', 'Анды, Амазония, Бразилия, Аргентина'],
    ['oc', 'Австралия и Океания', 'Австралия, Новая Зеландия, острова Тихого океана'],
]
# сфера: [название, оттенок (0–360), насыщенность %]
SPHERES = {
    'anc': ['Древний Ближний Восток и Египет', 46, 62],
    'gr': ['Греко-римский мир', 62, 58],
    'lat': ['Западный мир (католики и протестанты)', 128, 42],
    'orth': ['Православный мир и Россия', 356, 58],
    'isl': ['Исламский мир', 182, 48],
    'ir': ['Иранский мир', 310, 40],
    'st': ['Кочевники степи (тюрки, монголы)', 214, 52],
    'ind': ['Индийский мир', 28, 78],
    'chn': ['Китайский мир (Китай, Корея, Япония, Вьетнам)', 272, 42],
    'sea': ['Юго-Восточная Азия', 92, 45],
    'afr': ['Африканские государства', 22, 35],
    'amr': ['Цивилизации доколумбовой Америки', 160, 48],
    'col': ['Колонии европейских держав', 228, 16],
    'oth': ['Другие государства', 30, 8],
    'cul': ['Культуры и народы без государства', 40, 4],
}
ERAS = [
    ['Ранние цивилизации', -3500, -800, 'Бронзовый век: первые города, письменность и государства в долинах великих рек — Месопотамия, Египет, Инд, Хуанхэ. Около 1200 года до н. э. — катастрофа бронзового века.'],
    ['Античность', -800, 476, 'Железный век и классическая древность: Греция, Рим, Персия, империи Маурьев и Хань. Рождаются философия, мировые религии, римское право. Конец — падение Западной Римской империи (476).'],
    ['Средние века', 476, 1492, 'От падения Рима до открытия Америки: христианская Европа, Византия, исламские халифаты, Монгольская империя, Тан и Сун в Китае. Границы условны: в российской традиции конец Средних веков иногда относят к 1640 году.'],
    ['Новое время', 1492, 1918, 'Великие географические открытия, Реформация, колониальные империи, научная и промышленная революции, национальные государства. Конец — Первая мировая война.'],
    ['Новейшее время', 1918, NOW, 'Мировые войны, распад колониальных империй, холодная война, распад СССР, глобализация и цифровая эпоха.'],
]

reg = {r[0] for r in REGIONS}
items, events, ids, err = [], [], set(), []
for f in sorted(glob.glob(os.path.join(HERE, 'raw', '[1-4]_*.txt'))):
    for n, line in enumerate(open(f, encoding='utf-8'), 1):
        line = line.strip()
        if not line or line.startswith('#'): continue
        p = line.split('|')
        if len(p) not in (7, 8): err.append('%s:%d поля %d' % (os.path.basename(f), n, len(p))); continue
        i, name, a, b, r, s, d = p[:7]; fl = p[7] if len(p) > 7 else ''
        a, b = int(a), int(b)
        if i in ids: err.append('повтор id ' + i)
        if r not in reg: err.append('регион %s у %s' % (r, i))
        if s not in SPHERES: err.append('сфера %s у %s' % (s, i))
        if not a < b: err.append('годы %s' % i)
        if b > NOW: err.append('будущее %s' % i)
        ids.add(i); items.append([i, name, a, b, r, s, d, fl])
for n, line in enumerate(open(os.path.join(HERE, 'raw', '5_events.txt'), encoding='utf-8'), 1):
    line = line.strip()
    if not line or line.startswith('#'): continue
    p = line.split('|')
    if len(p) != 6: err.append('события:%d поля %d' % (n, len(p))); continue
    i, y, name, d, r, w = p
    if i in ids: err.append('повтор id ' + i)
    if r not in reg: err.append('регион %s у %s' % (r, i))
    ids.add(i); events.append([i, int(y), name, d, r, int(w)])
names = [x[1] for x in items]
for x in set(names):
    if names.count(x) > 1: err.append('повтор названия ' + x)
if err:
    print('\n'.join(err)); sys.exit(1)
items.sort(key=lambda x: (x[2], x[3]))
events.sort(key=lambda x: x[1])
out = {'now': NOW, 'regions': REGIONS, 'spheres': SPHERES, 'eras': ERAS, 'items': items, 'events': events}
json.dump(out, open(os.path.join(HERE, 'data.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
print('ok история: %d государств и культур, %d событий' % (len(items), len(events)))
